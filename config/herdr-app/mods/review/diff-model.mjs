// The diff as data, with no UI or herdr dependencies: what a row is, which files start folded, the file tree.

export const isLine = (r) => Boolean(r) && (r.k === "add" || r.k === "del" || r.k === "ctx");
/** A line's text as GPUI draws it: tabs as four spaces, spaces that never collapse. */
export const plain = (text) => String(text ?? "").replace(/\t/g, "    ").replace(/ /g, " ");

// Lockfiles, minified and built files, and files that say they are generated start folded.
const GENERATED = /(^|\/)(package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|poetry\.lock|Pipfile\.lock|Gemfile\.lock|composer\.lock|go\.sum|flake\.lock|lazy-lock\.json)$|\.min\.(js|css|mjs)$|\.map$|(^|\/)(dist|build|vendor|node_modules)\//;
// Kept on the file: the regexes over every file were most of a display rebuild.
export const isGenerated = (file) => (file.generated ??= GENERATED.test(file.path)
  || file.rows.slice(0, 12).some((r) => /@generated|DO NOT EDIT|auto-generated|autogenerated/i.test(r.text ?? "")));
export const lineCount = (file) => (file.lineCount ??= file.rows.filter(isLine).length);

/** Folders and files of the file list, folders first; a folder with one folder in it is one row. */
export function fileTree(files) {
  const root = { dirs: new Map(), files: [] };
  files.forEach((f, i) => {
    const parts = f.path.split("/");
    let node = root;
    for (const p of parts.slice(0, -1)) {
      if (!node.dirs.has(p)) node.dirs.set(p, { dirs: new Map(), files: [] });
      node = node.dirs.get(p);
    }
    node.files.push({ name: parts.at(-1), index: i });
  });
  const out = [];
  const walk = (node, depth, prefix) => {
    for (const [name, child] of [...node.dirs].sort((a, b) => a[0].localeCompare(b[0]))) {
      let label = name, n = child;
      while (n.dirs.size === 1 && !n.files.length) {
        const [[sub, next]] = [...n.dirs];
        label += `/${sub}`;
        n = next;
      }
      const path = `${prefix}${label}`;
      out.push({ dir: true, label, path, depth });
      walk(n, depth + 1, `${path}/`);
    }
    for (const f of node.files) out.push({ dir: false, label: f.name, index: f.index, depth, path: `${prefix}${f.name}` });
  };
  walk(root, 0, "");
  return out;
}
